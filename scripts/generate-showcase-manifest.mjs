#!/usr/bin/env node
// @ts-check
/**
 * Writes the component inventory the UI showcase renders its coverage list from.
 * Run with --check to fail when the committed manifest has drifted, which is how
 * CI notices a new component that nobody added a demo for.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const COMPONENTS = join(ROOT, 'static', 'js', 'components');
const OUT = join(ROOT, 'static', 'js', 'pages', 'admin', 'showcase-manifest.js');

/** @param {string} dir @returns {string[]} */
function walk(dir) {
  /** @type {string[]} */
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else if (extname(full) === '.js' && !full.endsWith('.test.js')) files.push(full);
  }
  return files;
}

const entries = walk(COMPONENTS)
  .map((file) => {
    const src = readFileSync(file, 'utf8');
    /** @type {Set<string>} */
    const exports = new Set();
    for (const m of src.matchAll(
      /^\s*export\s+(?:async\s+)?(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/gm,
    )) {
      exports.add(m[1]);
    }
    for (const m of src.matchAll(/^\s*export\s*\{([^}]+)\}/gm)) {
      for (const part of m[1].split(',')) {
        const name = part.trim().split(/\s+as\s+/).pop()?.trim();
        if (name) exports.add(name);
      }
    }
    return {
      module: relative(join(ROOT, 'static', 'js'), file).replaceAll('\\', '/'),
      exports: [...exports].sort(),
    };
  })
  .filter((entry) => entry.exports.length > 0)
  .sort((a, b) => a.module.localeCompare(b.module));

const banner = `// @ts-check
// Generated by scripts/generate-showcase-manifest.mjs. Do not edit by hand.
// Regenerate with: node scripts/generate-showcase-manifest.mjs
`;

const body = `${banner}
/** @type {{ module: string, exports: string[] }[]} */
export const COMPONENTS = ${JSON.stringify(entries, null, 2)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== body) {
    console.error('error: showcase manifest is stale.');
    console.error('Run `node scripts/generate-showcase-manifest.mjs` and commit the result.');
    process.exit(1);
  }
  console.log(`Showcase manifest is current (${entries.length} components).`);
  process.exit(0);
}

writeFileSync(OUT, body);
console.log(`Wrote ${relative(ROOT, OUT)} (${entries.length} components).`);
